const Font = {
  glyphs: {},
  cache: new Map(),
  SPACE: 4,
  LINE: 16,

  init() {
    for (const [ch, src] of Object.entries(GLYPHS)) {
      const rows = src.split('/');
      this.glyphs[ch] = { rows, w: Math.max(...rows.map((r) => r.length)) };
    }
  },

  glyphImage(ch, color) {
    let set = this.cache.get(color);
    if (!set) {
      set = new Map();
      this.cache.set(color, set);
    }
    let img = set.get(ch);
    if (!img) {
      const gl = this.glyphs[ch];
      img = Pix.fromRows(gl.rows, { '#': color });
      set.set(ch, img);
    }
    return img;
  },

  charWidth(ch) {
    if (ch === ' ') return this.SPACE;
    const gl = this.glyphs[ch] || this.glyphs['?'];
    return gl.w + 1;
  },

  width(text) {
    let w = 0;
    for (const ch of text) w += this.charWidth(ch);
    return Math.max(0, w - 1);
  },

  // Draw a single line. Shadow is offset right, down and diagonally, like
  // the GBA's text renderer.
  draw(g, text, x, y, color = '#484850', shadow = '#d0d0c8') {
    if (shadow) {
      this.drawRaw(g, text, x + 1, y, shadow);
      this.drawRaw(g, text, x, y + 1, shadow);
      this.drawRaw(g, text, x + 1, y + 1, shadow);
    }
    this.drawRaw(g, text, x, y, color);
  },

  drawRaw(g, text, x, y, color) {
    let cx = Math.round(x);
    const cy = Math.round(y);
    for (const ch of text) {
      if (ch === ' ') { cx += this.SPACE; continue; }
      const key = this.glyphs[ch] ? ch : '?';
      g.drawImage(this.glyphImage(key, color), cx, cy);
      cx += this.glyphs[key].w + 1;
    }
  },

  drawRight(g, text, right, y, color, shadow) {
    this.draw(g, text, right - this.width(text), y, color, shadow);
  },

  drawCenter(g, text, cx, y, color, shadow) {
    this.draw(g, text, Math.round(cx - this.width(text) / 2), y, color, shadow);
  },

  // Word-wrap to a pixel width. Explicit '\n' breaks are kept.
  wrap(text, maxW) {
    const out = [];
    for (const para of text.split('\n')) {
      let line = '';
      for (const word of para.split(' ')) {
        const test = line ? `${line} ${word}` : word;
        if (this.width(test) <= maxW || !line) line = test;
        else {
          out.push(line);
          line = word;
        }
      }
      out.push(line);
    }
    return out;
  },
};
